#!/usr/bin/env python3
"""Keep a package-contained CLI fixture synchronized with its authored owner."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/tritium-serve/tests/portable_fixture/mod.rs"
TARGET = ROOT / "crates/tritium-cli/tests/portable_fixture/mod.rs"
HEADER = b"// Generated by scripts/sync-cli-test-fixture.py. Do not edit.\n// Authored owner: crates/tritium-serve/tests/portable_fixture/mod.rs.\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if SOURCE.is_symlink() or TARGET.is_symlink():
        parser.error("fixture source and snapshot must be regular files")
    expected = HEADER + SOURCE.read_bytes()
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != expected:
            parser.error("CLI fixture drift: run scripts/sync-cli-test-fixture.py")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_bytes(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
